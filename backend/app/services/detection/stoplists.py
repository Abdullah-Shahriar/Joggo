def _build_country_set() -> frozenset[str]:
    names: set[str] = {
        "usa",
        "u.s.a.",
        "u.s.",
        "us",
        "uk",
        "u.k.",
        "uae",
        "u.a.e.",
        "united states",
        "united kingdom",
        "england",
        "scotland",
        "wales",
    }
    for country in pycountry.countries:
        for attr in ("name", "official_name", "common_name"):
            val = getattr(country, attr, None)
            if val:
                names.add(str(val).strip().lower())
    return frozenset(names)


COUNTRY_NAMES: frozenset[str] = _build_country_set()


def is_country(text: str) -> bool:
    return text.strip().lower() in COUNTRY_NAMES
